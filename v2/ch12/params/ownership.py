def _invert() -> dict:
    out: dict = {}
    dup = []
    for frag, paths in OWNERS.items():
        for path in paths:
            if path in out:
                dup.append(f"{path}: {out[path]} / {frag}")
            out[path] = frag
    if dup:
        raise RuntimeError(f"v1 키가 두 조각에 있음: {dup}")
    return out


V1_KEY_OWNER: dict = _invert()


def owner_of(path: str) -> Optional[str]:
    return V1_KEY_OWNER.get(path) or V1_CODE_ONLY_OWNER.get(path)


def split_path(path: str) -> tuple:
    """"ch2.MFC_SCALE_FACTORS.3" → ("ch2", "MFC_SCALE_FACTORS", "3"), "common.X" → ("common", "X", None)."""
    sec, rest = path.split(".", 1)
    if sec == CODE or "." not in rest:
        return sec, rest, None
    name, sub = rest.split(".", 1)
    return sec, name, sub


def v2_key_for(path: str) -> str:
    """v1 경로 → 이름 규칙의 v2 키."""
    sec, name, sub = split_path(path)
    base = name if sec in ("common", CODE) else f"{sec.upper()}_{name}"
    return base if sub is None else f"{base}_{sub.upper()}"


def path_for_key(key: str) -> str:
    """이름 규칙의 v2 키 → v1 경로(구역 접두어로 판단, 접두어 없으면 common)."""
    for sec in ("ch1", "ch2"):
        pre = sec.upper() + "_"
        if key.startswith(pre):
            return f"{sec}.{key[len(pre):]}"
    return f"common.{key}"


def v1_refs(key: str, v1_key: Optional[str] = None) -> tuple:
    """v2 키(와 v1_key)가 가리키는 v1 경로 후보. v1_key 가 구역 없는 이름이면 v2 키의 구역을 따른다."""
    if v1_key:
        ref = v1_key.strip()
        if ref.split(".", 1)[0] in SECTIONS + (CODE,) and "." in ref:
            return (ref,)
        if ref.startswith(("CH1_", "CH2_")):
            return (path_for_key(ref),)
        sec = path_for_key(key).split(".", 1)[0]
        return (f"{sec}.{ref}",) if sec != "common" else (f"common.{ref}", f"{CODE}.{ref}")
    path = path_for_key(key)
    if path.startswith("common."):
        return (path, f"{CODE}.{key}")
    return (path,)


def is_declared(sec: str, name: str) -> bool:
    """v1 로더가 그 구역에서 받아 주던 이름인가(v1 lib/_config_loader.py:270 hasattr — 대문자 이름만 본다)."""
    if sec not in SECTIONS:
        return False
    if name in V1_DECLARED["common"]:
        return True
    return sec != "common" and name in V1_DECLARED[sec]
